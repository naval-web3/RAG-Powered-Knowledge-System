/**
 * Interface strings, one dictionary per locale.
 *
 * English is the source: every other locale is checked against it, and any key
 * a locale is missing falls back to the English text rather than showing the
 * key. Keys are flat and namespaced by where they appear, so a string can be
 * traced to its screen without opening the component.
 *
 * {name} placeholders are filled at render time and inserted as text.
 *
 * Nothing the user or the model wrote belongs in here: conversation titles,
 * messages and document names stay in the language they were written in.
 *
 * Screens with a lot of copy keep their strings in a sibling file and are
 * merged in at the bottom, so no one dictionary grows past reading length.
 */
